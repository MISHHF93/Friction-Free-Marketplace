create or replace function public.current_user_is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.users u
    where u.id = auth.uid()
      and u.role in ('admin', 'super_admin')
      and u.status = 'active'
  );
$$;

create or replace function public.is_conversation_participant(conversation_uuid uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.conversations c
    where c.id = conversation_uuid
      and auth.uid() in (c.buyer_id, c.seller_id)
  );
$$;

create or replace function public.is_transaction_participant(transaction_uuid uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.transactions t
    where t.id = transaction_uuid
      and auth.uid() in (t.buyer_id, t.seller_id)
  );
$$;

-- -----------------------------------------------------------------------------
-- Updated-at triggers
-- -----------------------------------------------------------------------------

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'verification_levels','users','profiles','addresses','categories','listings',
    'listing_images','listing_videos','saved_searches','conversations','messages',
    'offers','transactions','escrow_payments','payouts','reviews','trust_scores',
    'reports','disputes','notifications','ai_agents','ai_tasks'
  ] loop
    execute format('drop trigger if exists set_%I_updated_at on public.%I', table_name, table_name);
    execute format('create trigger set_%I_updated_at before update on public.%I for each row execute function public.set_updated_at()', table_name, table_name);
  end loop;
end $$;

