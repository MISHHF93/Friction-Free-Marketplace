declare
  table_name text;
begin
  foreach table_name in array array[
    'verification_levels','users','profiles','addresses','categories','listings',
    'listing_images','listing_videos','listing_attributes','favorites','saved_searches',
    'conversations','messages','offers','transactions','escrow_payments','payouts',
    'reviews','trust_scores','reports','disputes','fraud_signals','notifications',
    'ai_agents','ai_tasks','search_events','analytics_events','admin_actions','audit_logs'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
  end loop;
end $$;

